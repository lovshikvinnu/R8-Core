`timescale 1ns / 1ps

module decoder_tb;

    integer passed;
    integer failed;

    reg  [15:0] instruction;

    wire [3:0] opcode;
    wire [1:0] ra;
    wire [1:0] rb;
    wire [9:0] immediate;
    wire [7:0] address;

    // Instantiate Decoder
    decoder uut (
        .instruction(instruction),
        .opcode(opcode),
        .ra(ra),
        .rb(rb),
        .immediate(immediate),
        .address(address)
    );

    // --------------------------------------------------
    // TEST TASK
    // --------------------------------------------------
    task check_decoder;
        input [15:0] test_instruction;
        input [3:0]  expected_opcode;
        input [1:0]  expected_ra;
        input [1:0]  expected_rb;
        input [9:0]  expected_immediate;
        input [7:0]  expected_address;

        begin
            instruction = test_instruction;
            #1;

            if ((opcode    == expected_opcode) &&
                (ra        == expected_ra) &&
                (rb        == expected_rb) &&
                (immediate == expected_immediate) &&
                (address   == expected_address)) begin

                $display("PASS: instruction = %h", test_instruction);
                passed = passed + 1;

            end else begin

                $display("FAIL: instruction = %h", test_instruction);

                $display("      Expected: OP=%h RA=%h RB=%h IMM=%h ADDR=%h",
                         expected_opcode,
                         expected_ra,
                         expected_rb,
                         expected_immediate,
                         expected_address);

                $display("      Got:      OP=%h RA=%h RB=%h IMM=%h ADDR=%h",
                         opcode,
                         ra,
                         rb,
                         immediate,
                         address);

                failed = failed + 1;
            end
        end
    endtask


    // --------------------------------------------------
    // TESTS
    // --------------------------------------------------
    initial begin

        passed = 0;
        failed = 0;
        instruction = 16'b0;

        // --------------------------------------------------
        // TEST 1: NOP
        // 0000 0000 0000 0000
        // --------------------------------------------------
        check_decoder(
            16'h0000,
            4'h0,
            2'b00,
            2'b00,
            10'h000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 2: ADD R1, R2
        // 0001 01 10 00000000
        // --------------------------------------------------
        check_decoder(
            16'b0001_01_10_00000000,
            4'h1,
            2'b01,
            2'b10,
            10'b1000000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 3: SUB R3, R1
        // 0010 11 01 00000000
        // --------------------------------------------------
        check_decoder(
            16'b0010_11_01_00000000,
            4'h2,
            2'b11,
            2'b01,
            10'b0100000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 4: AND R2, R3
        // 0011 10 11 00000000
        // --------------------------------------------------
        check_decoder(
            16'b0011_10_11_00000000,
            4'h3,
            2'b10,
            2'b11,
            10'b1100000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 5: OR R0, R1
        // 0100 00 01 00000000
        // --------------------------------------------------
        check_decoder(
            16'b0100_00_01_00000000,
            4'h4,
            2'b00,
            2'b01,
            10'b0100000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 6: XOR R3, R2
        // 0101 11 10 00000000
        // --------------------------------------------------
        check_decoder(
            16'b0101_11_10_00000000,
            4'h5,
            2'b11,
            2'b10,
            10'b1000000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 7: INC R1
        // Rb bits should be ignored
        // --------------------------------------------------
        check_decoder(
            16'b0110_01_00_00000000,
            4'h6,
            2'b01,
            2'b00,
            10'b0000000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 8: DEC R2
        // --------------------------------------------------
        check_decoder(
            16'b0111_10_00_00000000,
            4'h7,
            2'b10,
            2'b00,
            10'b0000000000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 9: LOADI R0, 10
        // 1000 00 0000001010
        // --------------------------------------------------
        check_decoder(
            16'b1000_00_0000001010,
            4'h8,
            2'b00,
            2'b00,
            10'd10,
            8'h0A
        );


        // --------------------------------------------------
        // TEST 10: LOADI R3, 255
        // --------------------------------------------------
        check_decoder(
            16'b1000_11_0011111111,
            4'h8,
            2'b11,
            2'b00,
            10'd255,
            8'hFF
        );


        // --------------------------------------------------
        // TEST 11: LOAD R1, address 0x25
        // --------------------------------------------------
        check_decoder(
            16'b1001_01_0000100101,
            4'h9,
            2'b01,
            2'b00,
            10'h025,
            8'h25
        );


        // --------------------------------------------------
        // TEST 12: STORE R2, address 0x80
        // --------------------------------------------------
        check_decoder(
            16'b1010_10_0010000000,
            4'hA,
            2'b10,
            2'b00,
            10'h080,
            8'h80
        );


        // --------------------------------------------------
        // TEST 13: JMP address 0x55
        // --------------------------------------------------
        check_decoder(
            16'b1011_0000_01010101,
            4'hB,
            2'b00,
            2'b00,
            10'b0001010101,
            8'h55
        );


        // --------------------------------------------------
        // TEST 14: BZ address 0xA0
        // --------------------------------------------------
        check_decoder(
            16'b1100_0000_10100000,
            4'hC,
            2'b00,
            2'b00,
            10'b0010100000,
            8'hA0
        );


        // --------------------------------------------------
        // TEST 15: HALT
        // --------------------------------------------------
        check_decoder(
            16'hD000,
            4'hD,
            2'b00,
            2'b00,
            10'h000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 16: RESERVED OPCODE 1110
        // --------------------------------------------------
        check_decoder(
            16'hE000,
            4'hE,
            2'b00,
            2'b00,
            10'h000,
            8'h00
        );


        // --------------------------------------------------
        // TEST 17: RESERVED OPCODE 1111
        // --------------------------------------------------
        check_decoder(
            16'hF000,
            4'hF,
            2'b00,
            2'b00,
            10'h000,
            8'h00
        );


        // --------------------------------------------------
        // FINAL SUMMARY
        // --------------------------------------------------
        $display("");
        $display("========================================");
        $display("         DECODER TEST SUMMARY");
        $display("========================================");
        $display("PASSED = %0d", passed);
        $display("FAILED = %0d", failed);
        $display("========================================");

        if (failed == 0)
            $display("ALL DECODER TESTS PASSED!");
        else
            $display("DECODER TESTS FAILED!");

        $finish;
    end

endmodule